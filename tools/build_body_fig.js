/* Build src/js/gfd-body-fig.js: the GFD anatomy figure (front, T-pose, no muscles picked) in light and
   dark, as SVG <symbol>s for the body measurement screens. It needs the reference generator with renderAtlas
   (illustrations/reference/gfd-exercise-art.js in the project files).
   Usage: node tools/build_body_fig.js [path/to/reference/gfd-exercise-art.js] */
const path = require('path'), fs = require('fs');
const A = require(path.resolve(process.argv[2] || '/mnt/project-files/illustrations/reference/gfd-exercise-art.js'));
let out = '';
for (const [th, tag] of [['light', 'L'], ['dark', 'D']]) {
  const svg = A.renderAtlas('front', th, [], { transparent: true });
  const ns = (svg.match(/id="(g\d+_)/) || [])[1];
  let inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  if (ns) inner = inner.split(ns).join('msf' + tag + '_');
  out += '<symbol id="msFig' + tag + '" viewBox="-152 -8 304 300">' + inner + '</symbol>';
}
const js = '/* GENERATED by tools/build_body_fig.js from the reference gfd-exercise-art.js (renderAtlas front). Do not edit. */\n' +
  'window.GFD_BODY_FIG=' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'js', 'gfd-body-fig.js'), js);
console.log('src/js/gfd-body-fig.js', js.length, 'bytes');
