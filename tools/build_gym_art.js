// Build src/js/gfd-exercise-art-gym.js, the generator for the approved commercial gym illustrations.
//
// Usage: node tools/build_gym_art.js <generator dir> [spec files...]
//   <generator dir> is the project's illustrations/generator folder (it holds gfd-gen.js; the engine is found next to it
//   in ../reference/exercises/gfd-exercise-art.js). Spec files are approved redraws (e.g. specs/chest-fix.js), named
//   relative to the generator dir. They replace the engine's drawing for their ids, exactly as on the review page.
// The output registers as window.GFDArtGym so the 5-day split keeps its own approved copy (gfd-exercise-art.js).
const fs = require('fs'), path = require('path');
const [genDir, ...specArgs] = process.argv.slice(2);
if (!genDir) { console.error('usage: node tools/build_gym_art.js <generator dir> [spec files...]'); process.exit(1); }
const GEN = path.resolve(genDir), genFile = path.join(GEN, 'gfd-gen.js'), genSrc = fs.readFileSync(genFile, 'utf8');
const specFiles = specArgs.map(f => path.resolve(GEN, f));
process.env.GFD_SPECS = specFiles.join(':') || path.join(GEN, 'no-specs');
const G = require(genFile);   // engine with these specs compiled, to read each spec's final form

// the engine, with its internal helpers exposed as _lib (the same patch gfd-gen.js and its review pages use)
const engineFile = path.join(GEN, '..', 'reference', 'exercises', 'gfd-exercise-art.js');
const names = genSrc.match(/const LIB_NAMES = `([^`]*)`/)[1].split(/\s+/).filter(Boolean);
const mark = '  const api = {', engine = fs.readFileSync(engineFile, 'utf8');
if (!engine.includes(mark)) throw new Error('engine api line not found');
const grab = '_lib: (() => { const o = {}; ' + names.map(n => `try { o.${n} = ${n}; } catch (e) {}`).join(' ') + ' return o; })(), ';
const tail = 'if (typeof module !== \'undefined\') module.exports = api; else root.GFDArt = api;';
if (!engine.includes(tail)) throw new Error('engine export line not found');
const patched = engine.replace(mark, mark + ' ' + grab).replace(tail, tail.replace('root.GFDArt', 'root.GFDArtGym'));

// the spec compiler, taken from gfd-gen.js as is
const a = genSrc.indexOf('function makeCompiler(A) {'), b = genSrc.indexOf('\n}\n', a);
if (a < 0 || b < 0) throw new Error('makeCompiler not found in gfd-gen.js');
const compiler = genSrc.slice(a, b + 2);

const specs = G.SPEC_IDS.map(id => { const ex = G.EX[id]; return { ...ex._spec, name: ex.name, main: ex.muscles.primary, help: ex.muscles.secondary }; });
const out = `// GENERATED by tools/build_gym_art.js from the project's illustrations generator: do not edit by hand.
// Engine: illustrations/reference/exercises/gfd-exercise-art.js. Approved redraws: ${specArgs.join(', ') || 'none'}.
// Registers as GFDArtGym; loaded on demand by exart.js for the approved gym exercises (ART_GYM there).
${patched}
(function (A) {
${compiler}
  const C = makeCompiler(A), SPECS = ${JSON.stringify(specs)};
  for (const s of SPECS) C.compile(s, {});
})(typeof module !== 'undefined' ? module.exports : this.GFDArtGym);
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'js', 'gfd-exercise-art-gym.js'), out);
console.log('gfd-exercise-art-gym.js built:', specs.length, 'redraws', `(${G.SPEC_IDS.join(', ')})`);
