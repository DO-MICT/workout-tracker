"""Write exercises.sql: loads exercises.json into public.exercises (paste into the Supabase SQL editor).
usage (from data/exercise-library): python3 tools/to_sql.py"""
import json

ex = json.load(open("exercises.json"))["exercises"]
cols = ["id", "name", "aliases", "training_type", "tags", "muscle_group", "primary_muscles", "secondary_muscles",
        "movement_pattern", "equipment", "req", "equipment_tier", "difficulty", "tracking", "unilateral", "sets", "reps",
        "form_cues", "common_mistakes", "regressions", "progressions", "safety", "video", "diagram", "notes"]
types = {"aliases": "text[]", "tags": "text[]", "primary_muscles": "text[]", "secondary_muscles": "text[]",
         "equipment": "text[]", "form_cues": "text[]", "common_mistakes": "text[]", "regressions": "text[]",
         "progressions": "text[]", "equipment_tier": "smallint", "sets": "smallint", "unilateral": "boolean"}
rec = ", ".join(f"{c} {types.get(c, 'text')}" for c in cols)
upd = ", ".join(f"{c} = excluded.{c}" for c in cols if c != "id")
out = [f"-- Loads {len(ex)} exercises into public.exercises. Safe to run again: existing rows are updated.",
       "-- Generated by tools/to_sql.py from exercises.json.", "begin;"]
for i in range(0, len(ex), 100):
    chunk = json.dumps([{c: e[c] for c in cols} for e in ex[i:i + 100]], ensure_ascii=False, separators=(",", ":"))
    assert "$ex$" not in chunk
    out.append(f"insert into public.exercises ({', '.join(cols)})\nselect {', '.join(cols)} from jsonb_to_recordset($ex${chunk}$ex$::jsonb)\n  as r({rec})\non conflict (id) do update set {upd};")
out.append("commit;")
out.append("select training_type, count(*) from public.exercises group by 1 order by 2 desc;")
open("exercises.sql", "w", encoding="utf-8").write("\n\n".join(out) + "\n")
print(len(ex), "rows")
