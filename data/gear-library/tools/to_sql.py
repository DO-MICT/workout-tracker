"""Write gear.sql: loads gear.json into public.gear and applies exercise-req-updates.json to public.exercises
(paste into the Supabase SQL editor).
usage (from data/gear-library): python3 tools/to_sql.py"""
import json
import re

items = json.load(open("gear.json"))["items"]
groups = json.load(open("app-equip.json"))
order = {}
for gi, g in enumerate(groups):
    for si, it in enumerate(g["items"]):
        order[it[0]] = (gi, si)
ids = {i["id"] for i in items}
assert set(order) == ids, "app-equip.json and gear.json list different ids"

cols = ["id", "name", "aliases", "keywords", "category", "subcategory", "app_group", "group_order", "sort_order", "tier",
        "setting", "description", "muscle_focus", "loading", "weight_options", "adjustability", "footprint", "space",
        "price_band", "requires", "substitutes", "signature_exercises", "exercise_ids", "buying_tips", "safety"]
types = {c: "text[]" for c in ["aliases", "muscle_focus", "requires", "substitutes", "signature_exercises", "exercise_ids"]}
types.update({"group_order": "smallint", "sort_order": "smallint", "tier": "smallint", "footprint": "jsonb"})
rows = []
for i in items:
    r = {c: i.get(c) for c in cols if c not in ("group_order", "sort_order")}
    r["group_order"], r["sort_order"] = order[i["id"]]
    for c in cols:
        if r[c] is None and c not in ("footprint", "space", "price_band"):
            r[c] = [] if types.get(c) == "text[]" else ""
    rows.append(r)

rec = ", ".join(f"{c} {types.get(c, 'text')}" for c in cols)
upd = ", ".join(f"{c} = excluded.{c}" for c in cols if c != "id")
out = [f"-- Loads {len(rows)} gear items into public.gear and sets the exact gear for the exercises that used stand-ins.",
       "-- Safe to run again: existing rows are updated. Generated by tools/to_sql.py from gear.json.", "begin;"]
for k in range(0, len(rows), 100):
    chunk = json.dumps(rows[k:k + 100], ensure_ascii=False, separators=(",", ":"))
    assert "$gear$" not in chunk
    out.append(f"insert into public.gear ({', '.join(cols)})\nselect {', '.join(cols)} from jsonb_to_recordset($gear${chunk}$gear$::jsonb)\n  as r({rec})\non conflict (id) do update set {upd};")

ups = json.load(open("exercise-req-updates.json"))["updates"]
for u in ups:
    for g in re.split(r"[,|]", u["new_req"]):
        assert g in ids, (u["id"], g)
vals = ",\n  ".join("('%s', '%s')" % (u["id"], u["new_req"]) for u in ups)
out.append(f"update public.exercises e set req = v.req\nfrom (values\n  {vals}\n) as v(id, req)\nwhere e.id = v.id;")
out.append("commit;")
out.append("select (select count(*) from public.gear) as gear_rows, "
           "(select count(*) from public.exercises where req ~ '(^|[,|])(highbench|ssb|pulloverm|yoke|log|tyre)([,|]|$)') as exact_req_rows;")
open("gear.sql", "w", encoding="utf-8").write("\n\n".join(out) + "\n")
print(len(rows), "gear rows,", len(ups), "req updates")
